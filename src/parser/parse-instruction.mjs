export function parseInstruction(tape, resolveLabelDepth = () => null) {
	const { atEnd, getCurrentCursor, getToken, peekToken, skipToken } = tape;
	const instrToken = peekToken(); // TODO: remove peek token here
	const position = getCurrentCursor();
	skipToken(); // Skip instruction token

	const refInstruction = parseRefInstruction(tape, instrToken, position);
	if (refInstruction) {
		return refInstruction;
	}

	const tableInstr = parseTableInstruction(tape, instrToken, position);
	if (tableInstr) {
		return tableInstr;
	}

	const memoryOps = parseMemoryOpsInstruction(tape, instrToken, position);
	if (memoryOps) {
		return memoryOps;
	}

	const atomicRMWInstr = parseAtomicRMWInstruction(tape, instrToken, position);
	if (atomicRMWInstr) {
		return atomicRMWInstr;
	}

	const atomicOps = parseAtomicsOpInstruction(tape, instrToken, position);
	if (atomicOps) {
		return atomicOps;
	}

	const simdLaneInstr = parseSIMDLaneBased(tape, instrToken, position);
	if (simdLaneInstr) {
		return simdLaneInstr;
	}

	const simdMemoryInstr = parseSIMDMemory(tape, instrToken, position);
	if (simdMemoryInstr) {
		return simdMemoryInstr;
	}

	const simdPlainInstr = parseSIMDPlainOpcode(instrToken, position);
	if (simdPlainInstr) {
		return simdPlainInstr;
	}

	// Continue with the original parseInstruction logic for other instructions
	const instrType = instrToken;
	if (stackInstructions.includes(instrType)) {
		// Handle stack instructions
		return { type: instrType, position };
	}
	if (instrType === "select") {
		// Handle select instruction explicitly
		// Check if this is a typed select with a result type
		if (!atEnd() && peekToken() === "(") {
			skipToken(); // Skip opening paren

			// Check for result type
			if (!atEnd() && peekToken() === "result") {
				skipToken(); // Skip 'result' keyword

				// Get the result type
				if (!atEnd()) {
					const resultType = getToken();

					// Skip closing paren
					if (!atEnd() && peekToken() === ")") {
						skipToken();
						// Return typed select instruction
						return { type: "select_t", resultType, position };
					}
				}
			}

			// If we couldn't parse a result type, skip to end of paren
			while (!atEnd() && peekToken() !== ")") {
				skipToken();
			}
			if (!atEnd() && peekToken() === ")") {
				skipToken();
			}
		}

		// Regular select instruction (no explicit type)
		return { type: "select", position };
	}
	if (instrType === "local.get" || instrType === "get_local") {
		const operand = getToken();
		return { type: "get_local", operand, position };
	}

	if (instrType === "local.set" || instrType === "set_local") {
		const operand = getToken();
		return { type: "set_local", operand, position };
	}

	if (instrType === "local.tee") {
		const operand = getToken();
		return { type: "local.tee", operand, position };
	}

	if (instrType === "global.get" || instrType === "get_global") {
		const operand = getToken();
		return { type: "global.get", operand, position };
	}

	if (instrType === "global.set" || instrType === "set_global") {
		const operand = getToken();
		return { type: "global.set", operand, position };
	}

	if (instrType === "i32.const") {
		const valueStr = getToken();
		try {
			return { type: "i32.const", value: parseI32Literal(valueStr), position };
		} catch (error) {
			throw createError(error.message, { position, found: valueStr });
		}
	}

	if (instrType === "i64.const") {
		const valueStr = getToken();
		try {
			return { type: "i64.const", value: parseI64Literal(valueStr), position };
		} catch (error) {
			throw createError(error.message, { position, found: valueStr });
		}
	}

	if (instrType === "f32.const") {
		const valueStr = getToken();
		try {
			const { value, bits } = parseF32Literal(valueStr);
			return { type: "f32.const", value, bits, position };
		} catch (error) {
			throw createError(error.message, { position, found: valueStr });
		}
	}

	if (instrType === "f64.const") {
		const valueStr = getToken();
		try {
			const { value, bits } = parseF64Literal(valueStr);
			return { type: "f64.const", value, bits, position };
		} catch (error) {
			throw createError(error.message, { position, found: valueStr });
		}
	}

	if (instrType === "br") {
		const label = getToken();
		return {
			type: "br",
			label,
			labelDepth: resolveLabelDepth(label),
			position,
		};
	}

	if (instrType === "br_if") {
		const label = getToken();
		return {
			type: "br_if",
			label,
			labelDepth: resolveLabelDepth(label),
			position,
		};
	}

	if (instrType === "br_table") {
		// Generated by 🤖
		// br_table takes multiple labels followed by a default label
		const labels = [];
		let defaultLabel = null;

		// Parse all the branch table labels until we reach the end
		while (!atEnd() && (isLabel(peekToken()) || peekToken().startsWith("$"))) {
			const label = getToken();
			labels.push({ label, position });
		}

		// The last label is always the default; the rest are case targets
		defaultLabel = labels.pop();

		// For named labels, return just the labels - the depths will be calculated during compilation
		return {
			type: "br_table",
			labels: labels.map((l) => l.label),
			labelDepths: labels.map((l) => resolveLabelDepth(l.label)),
			defaultLabel: defaultLabel.label,
			defaultLabelDepth: resolveLabelDepth(defaultLabel.label),
			position,
		};
	}
	// Handle data.drop instruction
	if (instrType === "data.drop") {
		// Handle named data segment reference
		if (!atEnd() && peekToken().startsWith("$")) {
			const dataLabel = getToken();
			return { type: "data.drop", dataLabel, position };
		}
		// Handle explicit numeric segment index
		let segmentIdx = null;
		if (!atEnd() && /^\d+$/.test(peekToken())) {
			segmentIdx = Number.parseInt(getToken(), 10);
		}
		return { type: "data.drop", segmentIdx, position };
	}

	// Handle memory.size instruction with optional memory reference
	if (instrType === "memory.size") {
		let memoryRef = null;
		if (!atEnd()) {
			if (peekToken().startsWith("$")) {
				memoryRef = getToken();
			} else if (/^\d+$/.test(peekToken())) {
				memoryRef = Number.parseInt(getToken(), 10);
			}
		}
		return { type: "memory.size", memoryRef, position };
	}

	// Handle memory.grow instruction with optional memory reference
	if (instrType === "memory.grow") {
		let memoryRef = null;
		if (!atEnd()) {
			if (peekToken().startsWith("$")) {
				memoryRef = getToken();
			} else if (/^\d+$/.test(peekToken())) {
				memoryRef = Number.parseInt(getToken(), 10);
			}
		}
		return { type: "memory.grow", memoryRef, position };
	}

	// Handle memory.fill instruction with optional memory reference
	if (instrType === "memory.fill") {
		let memoryRef = null;
		if (!atEnd()) {
			if (peekToken().startsWith("$")) {
				memoryRef = getToken();
			} else if (/^\d+$/.test(peekToken())) {
				memoryRef = Number.parseInt(getToken(), 10);
			}
		}
		return { type: "memory.fill", memoryRef, position };
	}

	// Handle memory.copy instruction with optional destination and source memory references
	if (instrType === "memory.copy") {
		let destMemoryRef = null;
		let srcMemoryRef = null;
		if (!atEnd()) {
			// First reference is destination
			if (peekToken().startsWith("$")) {
				destMemoryRef = getToken();
			} else if (/^\d+$/.test(peekToken())) {
				destMemoryRef = Number.parseInt(getToken(), 10);
			}
			// Second reference is source
			if (!atEnd()) {
				if (peekToken().startsWith("$")) {
					srcMemoryRef = getToken();
				} else if (/^\d+$/.test(peekToken())) {
					srcMemoryRef = Number.parseInt(getToken(), 10);
				}
			}
		}
		return { type: "memory.copy", destMemoryRef, srcMemoryRef, position };
	}

	// Handle memory.init instruction with optional memory reference and segment index
	if (instrType === "memory.init") {
		let memoryRef = null;
		// Default to segment 1 for backward compatibility with existing tests that use passive data segments
		let segmentIdx = 1;

		// Check for memory reference first (can be $name or number)
		if (!atEnd()) {
			if (peekToken().startsWith("$")) {
				memoryRef = getToken();
			} else if (/^\d+$/.test(peekToken())) {
				const token = getToken();
				// This could be either memory ref or segment idx
				// For now, treat first number as segment idx for backward compatibility
				segmentIdx = Number.parseInt(token, 10);
			}
		}

		return { type: "memory.init", memoryRef, segmentIdx, position };
	}

	// Handle elem.drop instruction
	if (instrType === "elem.drop") {
		// Check if next token is a number (element index)
		let elementIdx = 0; // Default to 0 if not specified
		if (!atEnd() && /^\d+$/.test(peekToken())) {
			elementIdx = Number.parseInt(peekToken(), 10);
			skipToken(); // Skip element index
		}
		return { type: "elem.drop", elementIdx, position };
	}

	if (instrType === "call") {
		const funcIndex = getToken();
		return { type: "call", functionName: funcIndex, position };
	}

	if (instrType === "call_indirect") {
		// Generated by 🤖
		const params = [];
		const results = [];
		let typeRef = null;
		let tableIndex = 0; // Default to first table

		// Handle inline type information in call_indirect
		// Process (param i32 i32) (result i32) format
		while (!atEnd() && peekToken() === "(") {
			skipToken(); // Skip opening paren

			if (!atEnd()) {
				const keyword = getToken();

				if (keyword === "type") {
					// Handle (type $typename) reference
					if (!atEnd()) {
						typeRef = getToken();
					}
				} else if (keyword === "param") {
					// Parse parameter types
					while (!atEnd() && peekToken() !== ")") {
						params.push(getToken());
					}
				} else if (keyword === "result") {
					// Parse result types
					while (!atEnd() && peekToken() !== ")") {
						results.push(getToken());
					}
				}

				// Skip closing paren
				if (!atEnd() && peekToken() === ")") {
					skipToken();
				}
			}
		}

		// Check for table index (optional, defaults to 0)
		if (!atEnd() && /^\d+$/.test(peekToken())) {
			tableIndex = Number.parseInt(getToken(), 10);
		}

		return {
			type: "call_indirect",
			params,
			results,
			typeRef,
			tableIndex,
			position,
		};
	}
	throw createError(`Unrecognized instruction: ${instrType}`, {
		code: "WAT_UNKNOWN_INSTRUCTION",
		position,
		found: instrType,
		hint: "Check the opcode spelling against the WebAssembly text format specification.",
		context: {
			instruction: instrType,
		},
		tape,
	});
}
