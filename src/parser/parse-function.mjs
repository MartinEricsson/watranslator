import { decodeWatString } from "../wat-string.mjs";
import { parseInstruction } from "./parse-instruction.mjs";
import { createError } from "./parse-util.mjs";

function isParamType(candidate) {
	return (
		candidate === "i32" ||
		candidate === "i64" ||
		candidate === "f32" ||
		candidate === "f64" ||
		candidate === "v128" ||
		candidate === "anyfunc" ||
		candidate === "funcref" ||
		candidate === "externref"
	);
}

export function parseFunction(tape) {
	const {
		atEnd,
		getCurrentCursor,
		getToken,
		peekToken,
		peekTokenN,
		skipToken,
	} = tape;
	let name = null;
	const params = [];
	const results = [];
	const locals = [];
	const instructions = [];
	const blockStack = []; // Stack to track nested blocks
	let exportName = null; // New variable to capture inline export
	let typeRef = null; // Store type reference if the function uses one
	let importInfo = null; // Generated by 🤖 - Store import info if function is imported

	const attachInstruction = (instr) => {
		if (blockStack.length > 0) {
			const parentBlock = blockStack[blockStack.length - 1];
			if (parentBlock.type === "if") {
				if (parentBlock.inElseBranch) {
					parentBlock.elseInstructions.push(instr);
				} else {
					parentBlock.thenInstructions.push(instr);
				}
			} else {
				parentBlock.instructions.push(instr);
			}
		} else {
			instructions.push(instr);
		}
	};

	const startBlockLike = (kind, position, isSExpression = false) => {
		let label = null;
		let resultType = null;

		if (!atEnd() && peekToken()?.startsWith("$")) {
			label = getToken();
		}

		if (!atEnd() && peekToken() === "(" && peekTokenN(1) === "result") {
			skipToken(); // "("
			skipToken(); // "result"

			const resultTypes = [];
			while (!atEnd() && peekToken() !== ")") {
				resultTypes.push(getToken());
			}

			if (!atEnd() && peekToken() === ")") {
				skipToken();
			}

			if (resultTypes.length === 1) {
				resultType = resultTypes[0];
			} else if (resultTypes.length > 1) {
				resultType = resultTypes;
			}
		}

		const blockInstr = {
			type: kind,
			label,
			resultType,
			instructions: [],
			position,
		};

		if (isSExpression) {
			blockInstr.sExpression = true;
		}

		attachInstruction(blockInstr);
		blockStack.push(blockInstr);
	};

	const resolveLabelDepth = (label) => {
		if (
			typeof label === "number" ||
			(typeof label === "string" && /^-?\d+$/.test(label))
		) {
			return Number.parseInt(label, 10);
		}

		for (let offset = 0; offset < blockStack.length; offset++) {
			const block = blockStack[blockStack.length - 1 - offset];
			if (block.label === label) {
				return offset;
			}
		}

		return null;
	};

	// Check for function name
	if (!atEnd() && peekToken().startsWith("$")) {
		name = getToken();
	}

	// Parse parameters, results, locals and body
	while (!atEnd()) {
		const currentToken = peekToken();

		if (currentToken === ")") {
			if (blockStack.length === 0) {
				break;
			}

			const currentBlock = blockStack[blockStack.length - 1];
			if (currentBlock?.sExpression) {
				currentBlock.endPosition = getCurrentCursor();
				blockStack.pop();
				skipToken();
				if (currentBlock.type === "if" && currentBlock.inElseBranch) {
					currentBlock.inElseBranch = false;
				}

				continue;
			}

			break;
		}

		if (currentToken === "(") {
			const tokenPos = getCurrentCursor();
			skipToken(); // Skip opening paren

			if (atEnd()) {
				throw createError("Unexpected end of input after '('");
			}

			const keyword = getToken();

			if (keyword === "loop" || keyword === "block") {
				startBlockLike(keyword, tokenPos, true);
				continue;
			}

			if (keyword === "if") {
				throw createError("S-expression style `if` is not supported", {
					code: "WAT_UNSUPPORTED_IF",
					position: tokenPos,
					found: keyword,
					hint: "Use stack-style `if ... else ... end` form instead.",
					tape,
				});
			}

			if (keyword === "type") {
				// Generated by 🤖
				// Handle type reference: (func (type $typeName) ...)
				// Get the type reference
				if (!atEnd()) {
					typeRef = peekToken();
					skipToken(); // Skip type reference
				}

				// Skip closing paren of type reference
				if (!atEnd() && peekToken() === ")") {
					skipToken();
				}
				continue;
			}

			if (keyword === "param") {
				// Parse parameter: (param $name type) or (param type)

				if (!atEnd() && peekToken().startsWith("$")) {
					// Named parameter: (param $name type)
					const name = getToken();

					if (!atEnd()) {
						const type = getToken();
						params.push({ name, type });
					}
				} else if (!atEnd()) {
					// Unnamed parameter: (param type)
					let type = peekToken();
					while (isParamType(type)) {
						skipToken();
						// Use index as name for unnamed parameters
						const name = params.length.toString();
						params.push({ name, type });
						type = peekToken();
					}
				}

				if (!atEnd() && peekToken() === ")") {
					skipToken();
				}
				continue;
			}

			if (keyword === "result") {
				while (!atEnd() && peekToken() !== ")") {
					results.push(peekToken());
					skipToken();
				}

				if (!atEnd() && peekToken() === ")") {
					skipToken();
				}
				continue;
			}

			if (keyword === "local") {
				let localName = null;
				let localType = null;

				if (!atEnd() && peekToken().startsWith("$")) {
					localName = getToken();
				}

				if (!atEnd()) {
					localType = getToken();
				}

				if (localType) {
					if (!localName) {
						localName = locals.length.toString();
					}
					locals.push({ name: localName, type: localType });
				}

				if (!atEnd() && peekToken() === ")") {
					skipToken();
				}
				continue;
			}

			if (keyword === "export") {
				if (
					!atEnd() &&
					peekToken().startsWith('"') &&
					peekToken().endsWith('"')
				) {
					const token = getToken();
					exportName = decodeWatString(token);
				}

				if (!atEnd() && peekToken() === ")") {
					skipToken();
				}
				continue;
			}

			if (keyword === "import") {
				let importModule = null;
				let importName = null;

				if (
					!atEnd() &&
					peekToken().startsWith('"') &&
					peekToken().endsWith('"')
				) {
					const moduleStr = getToken();
					importModule = decodeWatString(moduleStr);
				}

				if (
					!atEnd() &&
					peekToken().startsWith('"') &&
					peekToken().endsWith('"')
				) {
					const fieldStr = getToken();
					importName = decodeWatString(fieldStr);
				}

				if (importModule && importName) {
					importInfo = { module: importModule, field: importName };
				}

				if (!atEnd() && peekToken() === ")") {
					skipToken();
				}
				continue;
			}

			throw createError(`Unknown function field: ${keyword}`, {
				code: "WAT_UNKNOWN_FUNC_FIELD",
				position: tokenPos,
				found: keyword,
				expected: ["param", "result", "local", "export", "import", "type"],
				tape,
			});
		}

		if (peekToken() === "block") {
			skipToken(); // Skip 'block' keyword

			let label = null;
			let resultType = null;

			// Parse block label if present
			if (!atEnd() && peekToken().startsWith("$")) {
				label = getToken();
			}

			// Generated by 🤖
			// Parse result type if present
			if (!atEnd() && peekToken() === "(") {
				skipToken(); // Skip opening paren
				if (!atEnd() && peekToken() === "result") {
					skipToken(); // Skip 'result' keyword

					// Collect all result types
					const resultTypes = [];
					while (!atEnd() && peekToken() !== ")") {
						resultTypes.push(getToken());
					}

					// If there's only one result type, store it as a string
					// Otherwise, store as an array of types for multi-value returns
					if (resultTypes.length === 1) {
						resultType = resultTypes[0];
					} else if (resultTypes.length > 1) {
						resultType = resultTypes;
					}

					// Skip closing paren of result type
					if (!atEnd() && peekToken() === ")") {
						skipToken();
					}
				}
			}

			const blockInstr = {
				type: "block",
				label: label,
				resultType: resultType,
				instructions: [],
			};

			// Add this block to its parent's instructions or the main function body
			if (blockStack.length > 0) {
				const parentBlock = blockStack[blockStack.length - 1];
				parentBlock.instructions.push(blockInstr);
			} else {
				// Add to main function body
				instructions.push(blockInstr);
			}

			// Push this block to the stack to collect its instructions
			blockStack.push(blockInstr);
		} else if (peekToken() === "loop") {
			skipToken(); // Skip 'loop' keyword

			let label = null;
			let resultType = null;

			// Parse loop label if present
			if (!atEnd() && peekToken().startsWith("$")) {
				label = getToken();
			}

			// Parse result type if present
			if (!atEnd() && peekToken() === "(") {
				skipToken(); // Skip opening paren
				if (!atEnd() && peekToken() === "result") {
					skipToken(); // Skip 'result' keyword

					// Generated by 🤖
					// Collect all result types
					const resultTypes = [];
					while (!atEnd() && peekToken() !== ")") {
						resultTypes.push(getToken());
					}

					// If there's only one result type, store it as a string
					// Otherwise, store as an array of types for multi-value returns
					if (resultTypes.length === 1) {
						resultType = resultTypes[0];
					} else if (resultTypes.length > 1) {
						resultType = resultTypes;
					}

					// Skip closing paren of result type
					if (!atEnd() && peekToken() === ")") {
						skipToken();
					}
				}
			}

			const loopInstr = {
				type: "loop",
				label: label,
				resultType: resultType,
				instructions: [],
			};

			// Add this loop to its parent's instructions or the main function body
			if (blockStack.length > 0) {
				const parentBlock = blockStack[blockStack.length - 1];
				parentBlock.instructions.push(loopInstr);
			} else {
				// Add to main function body
				instructions.push(loopInstr);
			}

			// Push this loop to the stack to collect its instructions
			blockStack.push(loopInstr);
		} else if (peekToken() === "if") {
			skipToken(); // Skip 'if' keyword

			let resultType = null;

			// Generated by 🤖
			// Check for result type, handling multi-value results
			if (!atEnd() && peekToken() === "(") {
				skipToken(); // Skip opening paren
				if (!atEnd() && peekToken() === "result") {
					skipToken(); // Skip 'result' keyword

					// Collect all result types
					const resultTypes = [];
					while (!atEnd() && peekToken() !== ")") {
						resultTypes.push(getToken());
					}

					// If there's only one result type, store it as a string
					// Otherwise, store as an array of types for multi-value returns
					if (resultTypes.length === 1) {
						resultType = resultTypes[0];
					} else if (resultTypes.length > 1) {
						resultType = resultTypes;
					}

					// Skip closing paren of result type
					if (!atEnd() && peekToken() === ")") {
						skipToken();
					}
				}
			}

			const ifInstr = {
				type: "if",
				resultType: resultType,
				thenInstructions: [],
				elseInstructions: [],
				inElseBranch: false,
			};

			// Add this if to its parent's instructions or the main function body
			if (blockStack.length > 0) {
				const parentBlock = blockStack[blockStack.length - 1];
				parentBlock.instructions.push(ifInstr);
			} else {
				// Add to main function body
				instructions.push(ifInstr);
			}

			// Push this if block to the stack to collect its instructions
			blockStack.push(ifInstr);
		} else if (peekToken() === "else") {
			// Handle else branch - switch current if block to collect else instructions
			if (blockStack.length > 0) {
				const currentBlock = blockStack[blockStack.length - 1];
				if (currentBlock.type === "if") {
					currentBlock.inElseBranch = true;
				}
			}
			skipToken();
		} else if (peekToken() === "end") {
			// Handle end of a block - pop the current block from the stack
			if (blockStack.length > 0) {
				blockStack.pop();
			}
			skipToken();
		} else {
			// Parse other instructions (local.get, i32.add, etc.)
			const instr = parseInstruction(tape, resolveLabelDepth);

			// Add the instruction to the current block or function body
			if (blockStack.length > 0) {
				const currentBlock = blockStack[blockStack.length - 1];
				if (currentBlock.type === "if") {
					if (currentBlock.inElseBranch) {
						currentBlock.elseInstructions.push(instr);
					} else {
						currentBlock.thenInstructions.push(instr);
					}
				} else {
					// For blocks and loops
					currentBlock.instructions.push(instr);
				}
			} else {
				// Add to main function body
				instructions.push(instr);
			}
		}
	}

	// Return function object with additional inline export information
	const func = {
		name: name,
		parameters: params,
		locals: locals,
		results: results,
		instructions: instructions,
		typeRef: typeRef, // Include the type reference if present
	};

	// Generated by 🤖
	// If this function has an inline export, include it in the return value
	if (exportName) {
		func.export = exportName;
	}

	// If this function has an import, include it in the return value
	if (importInfo) {
		func.import = importInfo;
	}

	return func;
}
