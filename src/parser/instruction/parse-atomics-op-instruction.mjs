function readMemargAttributes(tape, instrToken, defaultAlign) {
	const { atEnd, getToken, peekToken } = tape;
	let align = defaultAlign;
	let offset = 0;
	const attrText = [instrToken];

	while (
		!atEnd() &&
		typeof peekToken() === "string" &&
		(peekToken().startsWith("offset=") || peekToken().startsWith("align="))
	) {
		attrText.push(getToken());
	}

	const joined = attrText.join(" ");
	const offsetMatch = joined.match(/offset=(\d+)/);
	if (offsetMatch?.[1]) {
		offset = Number.parseInt(offsetMatch[1], 10);
	}

	const alignMatch = joined.match(/align=(-?\d+)/);
	if (alignMatch?.[1]) {
		align = Number.parseInt(alignMatch[1], 10);
	}

	return { align, offset };
}

export function parseAtomicsOpInstruction(tape, instrToken, position) {
	const { atEnd } = tape;
	if (atEnd()) return null;

	// Handle atomic load/store instructions
	if (
		typeof instrToken === "string" &&
		(instrToken.startsWith("i32.atomic.") ||
			instrToken.startsWith("i64.atomic."))
	) {
		const is64Bit = instrToken.startsWith("i64.");
		// Generated by 🤖
		const is8Bit = instrToken.includes("8_") || instrToken.includes("store8");
		const is16Bit =
			instrToken.includes("16_") || instrToken.includes("store16");
		const is32Bit =
			instrToken.includes("32_") || instrToken.includes("store32");

		// Set default align value based on operation size
		let align;
		if (is8Bit) {
			align = 0; // 8-bit operations (1 byte = 2^0)
		} else if (is16Bit) {
			align = 1; // 16-bit operations (2 bytes = 2^1)
		} else if (is32Bit) {
			align = 2; // 32-bit operations (4 bytes = 2^2)
		} else {
			// Full-sized operations
			align = is64Bit ? 3 : 2; // 3 for i64 (8 bytes = 2^3), 2 for i32 (4 bytes = 2^2)
		}

		const memarg = readMemargAttributes(tape, instrToken, align);

		// Get the instruction type without attributes (the part before any space)
		const op = instrToken.split(/\s+/)[0];

		return {
			type: op,
			op,
			offset: memarg.offset,
			align: memarg.align,
			position,
		};
	}

	return null;
}
