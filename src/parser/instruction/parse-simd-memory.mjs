import { createError } from "../parse-util.mjs";

function parseOffsetAndAlign(tape, inlineAttributes = []) {
	const { atEnd, peekToken, skipToken } = tape;
	let align = 0; // Default alignment
	let offset = 0; // Default offset

	for (const attr of inlineAttributes) {
		if (attr.startsWith("align=")) {
			align = Number.parseInt(attr.split("=")[1], 10);
		} else if (attr.startsWith("offset=")) {
			offset = Number.parseInt(attr.split("=")[1], 10);
		}
	}

	// Process attributes in any order
	while (!atEnd()) {
		const nextToken = peekToken();

		if (nextToken.startsWith("align=")) {
			align = Number.parseInt(nextToken.split("=")[1], 10);
			skipToken();
		} else if (nextToken.startsWith("offset=")) {
			offset = Number.parseInt(nextToken.split("=")[1], 10);
			skipToken();
		} else {
			// Not a memory attribute, stop processing
			break;
		}
	}

	return { align, offset }; // Generated by 🤖
}

export function parseSIMDMemory(tape, instrToken, position) {
	const { atEnd, getToken, peekToken } = tape;
	if (typeof instrToken !== "string") {
		return false;
	}

	const [op, ...inlineAttributes] = instrToken.split(/\s+/);

	// Basic vector memory operations
	if (
		op === "v128.load" ||
		op === "v128.store" ||
		op === "v128.load8x8_s" ||
		op === "v128.load8x8_u" ||
		op === "v128.load16x4_s" ||
		op === "v128.load16x4_u" ||
		op === "v128.load32x2_s" ||
		op === "v128.load32x2_u" ||
		op === "v128.load8_splat" ||
		op === "v128.load16_splat" ||
		op === "v128.load32_splat" ||
		op === "v128.load64_splat" ||
		op === "v128.load32_zero" ||
		op === "v128.load64_zero"
	) {
		// Parse alignment and offset if present
		const { align, offset } = parseOffsetAndAlign(tape, inlineAttributes);

		// Create and return the instruction object
		return { type: op, align, offset, position };
	}

	// Lane-based loads and stores
	if (
		op === "v128.load8_lane" ||
		op === "v128.load16_lane" ||
		op === "v128.load32_lane" ||
		op === "v128.load64_lane" ||
		op === "v128.store8_lane" ||
		op === "v128.store16_lane" ||
		op === "v128.store32_lane" ||
		op === "v128.store64_lane"
	) {
		let laneIndex = 0;

		const { align, offset } = parseOffsetAndAlign(tape, inlineAttributes); // Generated by 🤖
		const inlineLaneIndex = inlineAttributes.find((attr) => /^\d+$/.test(attr));
		if (inlineLaneIndex !== undefined) {
			laneIndex = Number.parseInt(inlineLaneIndex, 10);
		}

		// Parse lane index
		if (
			inlineLaneIndex === undefined &&
			!atEnd() &&
			/^\d+$/.test(peekToken())
		) {
			laneIndex = Number.parseInt(getToken(), 10);
		}

		if (
			(op.includes("8_lane") && (laneIndex < 0 || laneIndex > 15)) ||
			(op.includes("16_lane") && (laneIndex < 0 || laneIndex > 7)) ||
			(op.includes("32_lane") && (laneIndex < 0 || laneIndex > 3)) ||
			(op.includes("64_lane") && (laneIndex < 0 || laneIndex > 1))
		) {
			throw createError(`${op} has invalid lane index: ${laneIndex}`);
		}

		return { type: op, align, offset, laneIndex, position };
	}

	return false;
}
