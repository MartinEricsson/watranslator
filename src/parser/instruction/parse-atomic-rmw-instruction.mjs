import { atEnd, getToken, peekToken } from "../tape.mjs";

function readMemargAttributes(instrToken, defaultAlign) {
	let align = defaultAlign;
	let offset = 0;
	const attrText = [instrToken];

	while (
		!atEnd() &&
		typeof peekToken() === "string" &&
		(peekToken().startsWith("offset=") || peekToken().startsWith("align="))
	) {
		attrText.push(getToken());
	}

	const joined = attrText.join(" ");
	const offsetMatch = joined.match(/offset=(\d+)/);
	if (offsetMatch?.[1]) {
		offset = Number.parseInt(offsetMatch[1], 10);
	}

	const alignMatch = joined.match(/align=(-?\d+)/);
	if (alignMatch?.[1]) {
		align = Number.parseInt(alignMatch[1], 10);
	}

	return { align, offset };
}

export function parseAtomicRMWInstruction(instrToken, position) {
	if (atEnd()) return null;

	// Generated by 🤖
	// Handle atomic RMW operations with inline offset/align attributes
	if (
		typeof instrToken === "string" &&
		instrToken.startsWith("i32.atomic.rmw")
	) {
		// Set proper alignment based on bit width
		let align = 2; // Default for i32 (4 bytes = 2^2)

		// Check if it's an 8-bit or 16-bit operation
		if (instrToken.includes("rmw8")) {
			align = 0; // 8-bit operations (1 byte = 2^0)
		} else if (instrToken.includes("rmw16")) {
			align = 1; // 16-bit operations (2 bytes = 2^1)
		}

		const memarg = readMemargAttributes(instrToken, align);

		// Get the base operation type
		const op = instrToken.split(/\s+/)[0];

		// Create instruction object with type field for AST compatibility
		// Generated by 🤖
		return { type: op, op, memarg, position };
	}

	// Handle i64.atomic.rmw operations
	if (
		typeof instrToken === "string" &&
		instrToken.startsWith("i64.atomic.rmw")
	) {
		// Set proper alignment based on bit width
		let align = 3; // Default for i64 (8 bytes = 2^3)

		// Check for different bit widths
		if (instrToken.includes("rmw8")) {
			align = 0; // 8-bit operations (1 byte = 2^0)
		} else if (instrToken.includes("rmw16")) {
			align = 1; // 16-bit operations (2 bytes = 2^1)
		} else if (instrToken.includes("rmw32")) {
			align = 2; // 32-bit operations (4 bytes = 2^2)
		}

		const memarg = readMemargAttributes(instrToken, align);

		// Get the base operation type
		const op = instrToken.split(/\s+/)[0];

		// Create instruction object with type field for AST compatibility
		// Generated by 🤖
		return { type: op, op, memarg, position };
	}

	return null;
}
