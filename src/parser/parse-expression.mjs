import { parseData } from "./parse-data.mjs";
import { parseExport } from "./parse-export.mjs";
import { parseFunction } from "./parse-function.mjs";
import { parseGlobal } from "./parse-global.mjs";
import { parseImport } from "./parse-import.mjs";
import { parseLocalVar } from "./parse-localvar.mjs";
import { parseMemory } from "./parse-memory.mjs";
import { parseModule } from "./parse-module.mjs";
import { createError, openParenthesis } from "./parse-util.mjs";

export function parseExpression(tape) {
	const { atEnd, getCurrentCursor, getToken, peekToken, skipToken } = tape;

	if (atEnd()) {
		return null;
	}

	const token = peekToken();
	const tokenPos = getCurrentCursor();

	if (token === "(") {
		const closeParenthesis = openParenthesis(tape);
		skipToken(); // Skip opening paren

		if (atEnd()) {
			throw createError("Unexpected end of input after '('");
		}

		const expressionType = getToken();

		if (expressionType === "module") {
			const module = parseModule(tape);
			module.position = tokenPos;
			return module;
		}

		if (expressionType === "func") {
			const funcExpr = parseFunction(tape);
			funcExpr.position = tokenPos;
			closeParenthesis();
			return funcExpr;
		}

		if (expressionType === "export") {
			const exportExpr = parseExport(tape);
			exportExpr.position = tokenPos;
			closeParenthesis();
			return exportExpr;
		}

		if (expressionType === "local") {
			// Parse local variable declaration
			const localExpr = parseLocalVar(tape);
			closeParenthesis();
			return { type: "local_decl", ...localExpr, position: tokenPos };
		}

		if (expressionType === "memory") {
			const memoryExpr = parseMemory(tape);
			closeParenthesis();
			return { type: "memory", ...memoryExpr, position: tokenPos };
		}

		if (expressionType === "data") {
			const dataExpr = parseData(tape);
			closeParenthesis();
			return { type: "data", ...dataExpr, position: tokenPos };
		}

		if (expressionType === "global") {
			// Parse global variable declaration
			const globalExpr = parseGlobal(tape);
			closeParenthesis();
			return { type: "global_decl", ...globalExpr, position: tokenPos };
		}

		if (expressionType === "import") {
			// Generated by 🤖
			// Parse import declaration
			const importExpr = parseImport(tape);
			importExpr.position = tokenPos;
			closeParenthesis();
			return { type: "import", ...importExpr, position: tokenPos };
		}

		throw createError(`Unknown expression type: ${expressionType}`, {
			code: "WAT_UNKNOWN_EXPRESSION",
			position: tokenPos,
			found: expressionType,
			expected: [
				"module",
				"func",
				"export",
				"local",
				"memory",
				"data",
				"global",
				"import",
			],
			tape,
		});
	}
	// Handle simple tokens
	skipToken();
	return { value: token, position: tokenPos };
}
