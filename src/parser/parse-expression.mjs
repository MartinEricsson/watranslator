import { createError, openParenthesis } from './parse-util.mjs';
import { peekToken, getCurrentCursor, atEnd, skipToken, getToken } from './tape.mjs';
import { parseData } from './parse-data.mjs';
import { parseMemory } from './parse-memory.mjs';
import { parseLocalVar } from './parse-localvar.mjs';
import { parseExport } from './parse-export.mjs';
import { parseGlobal } from './parse-global.mjs';
import { parseFunction } from './parse-function.mjs';
import { parseModule } from './parse-module.mjs';
import { parseImport } from './parse-import.mjs';

export function parseExpression() {
    if (atEnd()) {
        return null;
    }

    const currentToken = peekToken(); // Renamed to avoid conflict
    const tokenPos = getCurrentCursor();

    if (currentToken && currentToken.value === '(') {
        const closeParenthesis = openParenthesis();
        skipToken() // Skip opening paren

        if (atEnd()) {
            throw createError("Unexpected end of input after '('");
        }

        const expressionTypeToken = getToken(); // This is an object {value, line, column}
        const expressionType = expressionTypeToken.value;

        if (expressionType === 'module') {
            const module = parseModule();
            module.loc = tokenPos; // loc of '('
            return module;
        }

        if (expressionType === 'func') {
            const funcExpr = parseFunction();
            funcExpr.loc = tokenPos; // loc of '('
            closeParenthesis();
            return funcExpr;
        }

        if (expressionType === 'export') {
            const exportExpr = parseExport();
            exportExpr.loc = tokenPos; // loc of '('
            closeParenthesis();
            return exportExpr;
        }

        if (expressionType === 'local') {
            // Parse local variable declaration
            const localExpr = parseLocalVar();
            closeParenthesis();
            return { type: 'local_decl', ...localExpr, loc: tokenPos }; // loc of '('
        }

        if (expressionType === 'memory') {
            const memoryExpr = parseMemory();
            closeParenthesis();
            return { type: 'memory', ...memoryExpr, loc: tokenPos }; // loc of '('
        }

        if (expressionType === 'data') {
            const dataExpr = parseData();
            closeParenthesis();
            return { type: 'data', ...dataExpr, loc: tokenPos }; // loc of '('
        }

        if (expressionType === 'global') {
            // Parse global variable declaration
            const globalExpr = parseGlobal();
            closeParenthesis();
            return { type: 'global_decl', ...globalExpr, loc: tokenPos }; // loc of '('
        }

        if (expressionType === 'import') {
            // Generated by 🤖
            // Parse import declaration
            const importExpr = parseImport();
            // importExpr itself will have its loc set by parseImport,
            // but the wrapping expression starts at '(', so use tokenPos for the general import type
            closeParenthesis();
            return { type: 'import', ...importExpr, loc: tokenPos }; // loc of '('
        }

        // Skip unrecognized expressions
        while (!atEnd() && peekToken().value !== ')') {
            console.error("⚠️⚠️⚠️ Skip unrecognized expressions ", peekToken())
            skipToken()
        }
        closeParenthesis();
        return null;
    }
    // Handle simple tokens (not wrapped in parentheses)
    // These are typically instructions or values outside of s-expressions
    skipToken(); // Consume the token
    // currentToken is from peekToken, so it's the token we just skipped
    return { value: currentToken.value, loc: { line: currentToken.line, column: currentToken.column } };
}