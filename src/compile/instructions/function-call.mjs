import { encodeULEB128, resolveFunctionIndex } from "../compile-utils.mjs";
import wasmConstants from "../constants.mjs";
import { createError } from "./error.mjs";

const { INSTR } = wasmConstants;

export function compileFunctionCall(
	instr,
	body,
	module,
	func,
	moduleFunctions,
) {
	if (instr.type === "call") {
		body.push(INSTR.CALL);

		const funcIndex = resolveFunctionIndex(instr.functionName, module);

		if (funcIndex === -1) {
			throw createError(
				instr,
				func,
				module,
				`Unknown function: ${instr.functionName}. Function must be defined or imported before it can be called.`,
			);
		}

		// Type checking for function parameters
		const calledFunc = moduleFunctions[funcIndex];
		if (calledFunc?.parameters) {
			// TODO: Implement stack-based parameter validation
			// This would require tracking the stack state throughout function compilation
		}

		body.push(...encodeULEB128(funcIndex));

		return true;
	}

	if (instr.type === "call_indirect") {
		// Generated by 🤖
		body.push(INSTR.CALL_INDIRECT);

		try {
			let typeIndex = instr.typeIndex ?? 0;

			if (instr.typeRef && module && module.types) {
				// If a type reference was specified (e.g., type $i32_i32_to_i32)
				// Find the corresponding type in the module's type section
				const typeRefName = instr.typeRef;
				const typeEntry = module.types.find(
					(type) => type.name === typeRefName,
				);

				if (typeEntry) {
					typeIndex = typeEntry.typeIndex ?? typeIndex;
				} else {
					throw createError(
						instr,
						func,
						module,
						`Unknown type reference: ${typeRefName}`,
					);
				}
			}

			// Push the type index as LEB128 encoded value
			body.push(...encodeULEB128(typeIndex));

			// Table index (required in WebAssembly binary format)
			// In MVPv1 this must be 0
			body.push(0x00);

			return true;
		} catch (err) {
			throw createError(
				instr,
				func,
				module,
				`Invalid indirect call: ${err.message}`,
			);
		}
	}

	return false;
}
